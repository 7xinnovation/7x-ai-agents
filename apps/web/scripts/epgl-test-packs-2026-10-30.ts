/**
 * Write one test pack per kind of submission (30 October 2026).
 *
 * Each pack is a folder a tester can be handed on its own: the documents that
 * product needs, and a TESTING.md that says what to say and what to watch.
 * The documents come from the catalogue entry for the pack's product, so a
 * pack is short of a file only if EPGL's catalogue has a document this
 * generator has never been taught to draw -- and then it says which one and
 * writes nothing.
 *
 * Pack 01 is the 22 October pack and is NOT written by this script. Testers
 * already have it, its documents are a regression fixture pinned by
 * test-epgl-test-pack-2026-10-28, and it is regenerated by its own script.
 * This one copies it into place so the set is complete in one folder.
 *
 * Run from apps/web:
 *   npx tsx scripts/epgl-test-packs-2026-10-30.ts [--out <dir>] [--only <pack dir>]
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { html } from "./epgl-test-pack-2026-10-28";
import { BUILDERS, PARTNER2_DOCS, SCENARIOS, type Doc, type Scenario } from "./lib/epglTestPacks";

const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const arg = (name: string) => {
  const i = process.argv.indexOf(name);
  return i !== -1 ? process.argv[i + 1] : undefined;
};
const OUT = resolve(arg("--out") ?? resolve(process.cwd(), "../../../EPGL-2.0-test-packs"));
const ONLY = arg("--only");
const CATALOGUE = resolve(process.cwd(), "scripts/fixtures/epgl-catalogue-2026-10-21.json");
/** The 22 October pack, copied in as pack 01 rather than regenerated here. */
const PACK01_SRC = resolve(process.cwd(), "../../../EPGL-2.0-test-pack-2026-10-22");
const PACK01_DIR = "01-cep30-sme-uae-domestic";

interface Product {
  code: string;
  name?: { en?: string; ar?: string };
  conditionalIssuance?: boolean;
  fees?: { amount?: number }[];
  documents?: { documentType: string; required?: boolean; requiredWhen?: string; validityRequired?: boolean }[];
}

/**
 * The order a pack numbers its files in, which is roughly the order the
 * assistant asks for them: the licence first because it fills the most fields,
 * then the company's own papers, then the people, then the declarations.
 * Anything not named here sorts after, alphabetically, rather than being
 * dropped -- a new document EPGL add should appear in the pack even before
 * somebody decides where it belongs.
 */
const ORDER = [
  "Trade Licence",
  "Trade Licence / Initial Name Approval",
  "Memorandum of Association",
  "Copy of Passport",
  "Copy of Emirates ID",
  "Beneficial Ownership Declaration",
  "SME Licence (federal or local government)",
  "Lease Contract",
  "Insurance Certificate (goods in transit)",
  "Municipal Food Safety Clearance",
  "Pharmaceutical Handling Authorisation",
  "Cold-chain Capability Declaration",
  "Storage Premises Declaration",
  "Intermediation Model Declaration",
  "Data Handling Declaration",
  "Operator Contracts (sample)",
  "Locker / PUDO Site Locations and Contracts",
  "Principal Licensee Contract",
  "Liability and Indemnity Declaration",
  "Operational Fleet Declaration",
  "Operational Standards Self-declaration",
];

const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const money = (n: number) => `AED ${n.toLocaleString("en-AE")}`;

export function productFor(code: string): Product {
  const catalogue = JSON.parse(readFileSync(CATALOGUE, "utf8")) as { products: Product[] };
  const p = catalogue.products.find((x) => x.code === code);
  if (!p) throw new Error(`${code} is not in the catalogue`);
  return p;
}

/** Catalogue document types for a product, in the pack's numbering order. */
export function documentTypesFor(p: Product): string[] {
  const types = (p.documents ?? []).map((d) => d.documentType);
  return [...types].sort((a, b) => {
    const ia = ORDER.indexOf(a), ib = ORDER.indexOf(b);
    if (ia !== -1 && ib !== -1) return ia - ib;
    if (ia !== -1) return -1;
    if (ib !== -1) return 1;
    return a.localeCompare(b);
  });
}

/**
 * Every file in a pack, numbered.
 *
 * Partner 2's identity documents sit after the catalogue's, because they are
 * ours rather than EPGL's -- the MOA names two partners and the journey asks
 * for both -- and a tester reading down the folder should meet the catalogue's
 * list first.
 */
export function docsFor(s: Scenario): Doc[] {
  const types = documentTypesFor(productFor(s.code));
  const unknown = types.filter((t) => !BUILDERS[t]);
  if (unknown.length) {
    throw new Error(
      `${s.code}: the catalogue asks for ${unknown.map((u) => `"${u}"`).join(", ")} and this generator cannot draw ` +
      `${unknown.length === 1 ? "it" : "them"}. Add a builder to lib/epglTestPacks before writing this pack.`
    );
  }
  const built = types.map((t) => ({ ...BUILDERS[t]!(s.company), file: `${slug(t)}.pdf` }));
  /**
   * OUR OWN trade licence slot, which the CEP30 catalogue does not name.
   *
   * `trade_license` sits unconditioned in the `documents` step and is asked on
   * every run whatever the product -- it is the slot the extraction reads the
   * company off, and it was never merged into the catalogue's, because the
   * catalogue has TWO licence slots and a slot carries one type (the open
   * question for EPGL). The four permits name "Trade Licence" themselves so
   * the file is already there; the CEP30 products name only "Trade Licence /
   * Initial Name Approval", so without this a CEP30 pack is one file short of
   * what the assistant asks for.
   */
  const ours = types.includes("Trade Licence")
    ? []
    : [{ ...BUILDERS["Trade Licence"]!(s.company), file: "trade-licence.pdf" }];
  const all = [...ours, ...built, ...PARTNER2_DOCS];
  return all.map((d, i) => ({ ...d, file: `${String(i + 1).padStart(2, "0")}-${d.file}` }));
}

